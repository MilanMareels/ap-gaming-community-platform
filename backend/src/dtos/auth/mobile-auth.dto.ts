import { ApiProperty } from '@nestjs/swagger';
import { IsNotEmpty, IsString, Matches } from 'class-validator';

const BASE64URL = /^[A-Za-z0-9_-]{43,128}$/;

export class MobileHandoffQueryDto {
  @ApiProperty({
    description: 'PKCE S256 challenge: base64url(sha256(verifier)), generated by the mobile app',
    example: 'E9Melhoa2OwvFrEMTJguCHaoeK1t8URWbuGJSstw-cM',
  })
  @IsString()
  @Matches(BASE64URL)
  challenge!: string;
}

export class MobileTokenRequestDto {
  @ApiProperty({ description: 'Handoff code received on the app callback URL' })
  @IsString()
  @IsNotEmpty()
  code!: string;

  @ApiProperty({ description: 'PKCE verifier matching the challenge sent to /auth/mobile/handoff' })
  @IsString()
  @Matches(BASE64URL)
  verifier!: string;
}

export class MobileTokenResponseDto {
  @ApiProperty({ description: 'Bearer token for the Authorization header' })
  token!: string;
}
